/** Generated navigation. `index.md` is the small view injected into every session:
 * standing rules plus an Active set held to a character budget. `catalog.md` lists
 * everything for people and is never injected. Both are pure functions of concept
 * metadata and the Active set, which `index.md` itself records. */
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { STATE_DIR, loadConcepts, type Concept, type Finding } from "./store.js";
import { idleSessions, readUsage, recordUsage, type UsageStats } from "./usage.js";

export interface ViewConfig { indexBudget: number; demoteIdleSessions: number }
export const DEFAULT_VIEW: ViewConfig = { indexBudget: 2000, demoteIdleSessions: 20 };

export function viewConfig(bundle: string): ViewConfig {
	let file: Partial<ViewConfig> = {};
	try { file = JSON.parse(readFileSync(join(bundle, STATE_DIR, "config.json"), "utf8")) ?? {}; } catch { /* defaults */ }
	const pick = (env: string | undefined, value: unknown, fallback: number, min: number) => {
		const n = env !== undefined && env !== "" ? Number(env) : typeof value === "number" ? value : fallback;
		return Number.isSafeInteger(n) && n >= min ? n : fallback;
	};
	return {
		indexBudget: pick(process.env.OKF_INDEX_BUDGET, file.indexBudget, DEFAULT_VIEW.indexBudget, 0),
		demoteIdleSessions: pick(process.env.OKF_DEMOTE_IDLE_SESSIONS, file.demoteIdleSessions, DEFAULT_VIEW.demoteIdleSessions, 1),
	};
}

export const isPinned = (c: Concept) => c.pinned || c.id.startsWith("convention/");
const isRetired = (c: Concept) => c.status === "deprecated";
const oneLine = (text: string) => text.replace(/\s+/g, " ").trim();
const entry = (c: Concept) => `* [${oneLine(c.title).replace(/[\[\]]/g, "")}](${c.file}) - ${oneLine(c.description)}`;

const HEADER = `---\nokf_version: "0.2"\ngenerated_by: pi-okf-agent-memory\n---\n\n# Knowledge\n`;

/** The Active set is whatever the committed index lists, so every machine agrees on it. */
export function parseActive(index: string): string[] | null {
	if (!index.includes("generated_by: pi-okf-agent-memory")) return null;
	const section = /^## Active\n([\s\S]*?)(?=^## )/m.exec(index + "\n## ")?.[1] ?? "";
	return [...section.matchAll(/^\* \[[^\]]*\]\(([^)]+)\.md\)/gm)].map(m => m[1]!);
}

export function render(concepts: Concept[], active: string[]): { index: string; catalog: string } {
	const sorted = [...concepts].sort((a, b) => a.id < b.id ? -1 : 1);
	const pinned = sorted.filter(isPinned);
	const activeSet = new Set(active);
	const shown = sorted.filter(c => activeSet.has(c.id) && !isPinned(c));
	const rest = sorted.length - pinned.length - shown.length;
	const parts = [HEADER];
	if (!sorted.length) parts.push("No concepts yet.\n");
	if (pinned.length) parts.push(`## Standing rules\n${pinned.map(entry).join("\n")}\n`);
	if (shown.length) parts.push(`## Active\n${shown.map(entry).join("\n")}\n`);
	if (rest > 0) {
		const areas = new Map<string, number>();
		for (const c of sorted) if (!isPinned(c) && !activeSet.has(c.id)) { const area = c.id.includes("/") ? c.id.slice(0, c.id.indexOf("/") + 1) : "top level"; areas.set(area, (areas.get(area) ?? 0) + 1); }
		parts.push(`## Not shown\n${rest} more concept${rest === 1 ? "" : "s"} (${[...areas].map(([a, n]) => `${a} ${n}`).join(", ")}). Find them with memory_search; [catalog.md](catalog.md) lists every ID.\n`);
	}
	const groups = new Map<string, Concept[]>();
	for (const c of sorted) { const dir = c.id.includes("/") ? c.id.slice(0, c.id.lastIndexOf("/") + 1) : ""; (groups.get(dir) ?? groups.set(dir, []).get(dir)!).push(c); }
	const tier = (c: Concept) => isPinned(c) ? "pinned" : activeSet.has(c.id) ? "active" : isRetired(c) ? "deprecated" : "catalog";
	const catalog = [`# Knowledge catalog\n\nGenerated by pi-okf-agent-memory; edit concepts, not this file. Every concept is listed here.\n\`pinned\` and \`active\` concepts also appear in [index.md](index.md), which is loaded into each session;\n\`catalog\` concepts are reachable by search or ID only.\n`];
	for (const [dir, list] of [...groups].sort(([a], [b]) => a < b ? -1 : 1)) {
		catalog.push(`## ${dir || "Top level"}\n${list.map(c => `* [${oneLine(c.title).replace(/[\[\]]/g, "")}](${c.file}) \`${c.id}\` (${tier(c)}) - ${oneLine(c.description)}`).join("\n")}\n`);
	}
	return { index: parts.join("\n"), catalog: catalog.join("\n") };
}

function read(path: string): string | null { try { return readFileSync(path, "utf8"); } catch { return null; } }

/** Read-only: is the committed navigation what the concepts would generate? */
export function viewFindings(bundle: string, concepts: Concept[]): Finding[] {
	const index = read(join(bundle, "index.md")) ?? "";
	const active = parseActive(index);
	if (active === null) return [{ code: "index-stale", file: "index.md", message: "index.md is not in the generated format; run memory_validate or /memory-upgrade to regenerate it." }];
	const expected = render(concepts, active);
	const findings: Finding[] = [];
	if (index !== expected.index) findings.push({ code: "index-stale", file: "index.md", message: "index.md does not match concept metadata; it is regenerated on the next memory write or memory_validate." });
	if (read(join(bundle, "catalog.md")) !== expected.catalog) findings.push({ code: "index-stale", file: "catalog.md", message: "catalog.md does not match concept metadata; it is regenerated on the next memory write or memory_validate." });
	return findings;
}

export interface Refresh { changed: string[]; active: string[]; promoted: string[]; demoted: string[] }

/** Choose the Active set and rewrite navigation if it differs. Promotion is immediate;
 * idle demotion only happens when `rebalance` is set (maintenance, upgrades, commands). */
export function refreshView(bundle: string, options: { promote?: string[]; demote?: string[]; rebalance?: boolean; concepts?: Concept[]; stats?: UsageStats } = {}): Refresh {
	const concepts = options.concepts ?? loadConcepts(bundle).concepts;
	const config = viewConfig(bundle);
	const byId = new Map(concepts.map(c => [c.id, c]));
	const eligible = (id: string) => { const c = byId.get(id); return !!c && !isPinned(c) && !isRetired(c); };
	const previous = parseActive(read(join(bundle, "index.md")) ?? "");
	const before = (previous ?? []).filter(eligible);
	let stats = options.stats ?? readUsage(bundle);
	const demote = new Set(options.demote ?? []);
	let chosen = new Set(before);
	if (options.rebalance || previous === null) {
		// Start the idle clock for concepts the ledger has never seen (pulled, hand-written, pre-ledger).
		const unseen = concepts.filter(c => !stats.concepts[c.id]).map(c => c.id);
		if (unseen.length) { recordUsage(bundle, "seen", unseen); stats = readUsage(bundle); }
		if (stats.available) {
			for (const id of [...chosen]) if (idleSessions(stats, id) >= config.demoteIdleSessions) chosen.delete(id);
			for (const c of concepts) if (eligible(c.id) && stats.concepts[c.id]?.lastStrong !== undefined && idleSessions(stats, c.id) < config.demoteIdleSessions) chosen.add(c.id);
		}
		// First generation with no usable history: start from the most recently written
		// concepts rather than an empty index. Use then takes over.
		if (previous === null && !chosen.size) for (const c of concepts) if (eligible(c.id)) chosen.add(c.id);
	}
	for (const id of options.promote ?? []) if (eligible(id)) chosen.add(id);
	for (const id of demote) chosen.delete(id);
	// Most recently used first; the budget drops the tail.
	const promoted = new Set(options.promote ?? []);
	const rank = (id: string) => {
		const u = stats.concepts[id];
		return [promoted.has(id) ? 1 : 0, u?.lastStrong ?? -1, u?.lastAny ?? -1, Date.parse(byId.get(id)!.updated ?? "") || 0] as const;
	};
	const ordered = [...chosen].sort((a, b) => {
		const ra = rank(a), rb = rank(b);
		for (let i = 0; i < ra.length; i++) if (ra[i] !== rb[i]) return rb[i]! - ra[i]!;
		return a < b ? -1 : 1;
	});
	const active: string[] = [];
	let used = 0;
	for (const id of ordered) {
		const cost = entry(byId.get(id)!).length + 1;
		// Strict cut-off keeps the set predictable; one oversized entry may still stand alone.
		if (used + cost > config.indexBudget && (active.length || config.indexBudget === 0)) break;
		active.push(id); used += cost;
	}
	active.sort();
	const { index, catalog } = render(concepts, active);
	const changed: string[] = [];
	for (const [name, text] of [["index.md", index], ["catalog.md", catalog]] as const) {
		if (read(join(bundle, name)) !== text) { writeFileSync(join(bundle, name), text); changed.push(name); }
	}
	const was = new Set(before), now = new Set(active);
	return { changed, active, promoted: active.filter(id => !was.has(id)), demoted: before.filter(id => !now.has(id)) };
}

/** Per-directory index files from the old layout are replaced by catalog.md. */
export function removeLegacyIndexes(bundle: string): string[] {
	const removed: string[] = [];
	const walk = (dir: string, prefix: string) => {
		for (const item of readdirSync(dir, { withFileTypes: true })) {
			if (item.name.startsWith(".") || item.isSymbolicLink() || !item.isDirectory()) continue;
			const path = `${prefix}${item.name}/`;
			if (existsSync(join(dir, item.name, "index.md"))) { rmSync(join(dir, item.name, "index.md")); removed.push(`${path}index.md`); }
			walk(join(dir, item.name), path);
		}
	};
	walk(bundle, "");
	return removed;
}
